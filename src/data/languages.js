const capitalize = (s) => s.charAt(0).toLocaleUpperCase() + s.slice(1);

/** Display name of an (English-keyed) language in the UI language. */
export function languageName(english, lang) {
  if (lang === "es") return capitalize(LANGUAGE_NAMES[english]?.[0] ?? english);
  if (lang === "fr") return capitalize(LANGUAGE_NAMES[english]?.[1] ?? english);
  return english;
}

/** Every accepted spelling of a language (English + translations). */
export function languageSpellings(english) {
  return [english, ...(LANGUAGE_NAMES[english] ?? [])];
}
